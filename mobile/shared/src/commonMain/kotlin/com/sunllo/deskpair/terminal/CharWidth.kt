    fun of(codePoint: Int): Int = when {
        codePoint < 0x7F -> 1
        codePoint < 0xA0 -> 0
        within(zero, codePoint) -> 0
        within(wide, codePoint) -> 2
        else -> 1
    }

    /** Binary search over sorted [start, end] pairs. */
    private fun within(ranges: IntArray, cp: Int): Boolean {
        var lo = 0
        var hi = ranges.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                cp < ranges[mid * 2] -> hi = mid - 1
                cp > ranges[mid * 2 + 1] -> lo = mid + 1
                else -> return true
            }
        }

        return false
    }
}
