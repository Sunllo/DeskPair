package com.sunllo.deskpair.terminal

/**
 * How many cells a character takes: 0 for combining marks and zero-width characters, 2 for East Asian wide
 * and fullwidth characters and emoji, 1 for the rest.
 *
 * The desktop uses the Wcwidth package, which has no Kotlin Multiplatform port. This is its answer for the
 * ranges that matter on a terminal -- CJK, Hangul, kana, fullwidth forms, the emoji blocks, combining marks --
 * without the long tail of rarely printed scripts. Where they could disagree the shared vectors say which
 * is right, and none of the vectors lives in that tail.
 */
