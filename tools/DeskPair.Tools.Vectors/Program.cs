    var cases = new JsonArray();
    foreach ((string name, DeskPair.Core.Config.ConnectLink link) in new[]
    {
        ("full", new DeskPair.Core.Config.ConnectLink
        {
            Id = "123456789",
            RendezvousServer = "203.0.113.10:21116",
            ServerPublicKeyBase64 = serverKey,
            DeviceName = "Studio-Mac-mini",
            Password = "t4nq7zkp2xmr",
        }),
