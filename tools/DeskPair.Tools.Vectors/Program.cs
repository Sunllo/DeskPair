// Emits the conformance vectors the Kotlin client is checked against.
//
// The whole point is that these come out of the shipping code, not out of a second reading of it. Every
// value below is produced by calling DeskPair.Protocol itself, so a change to the handshake that
// nobody mirrors in Kotlin turns into a failing test rather than a session that silently does not connect —
// or worse, one that connects with keys derived a different way.
//
// Inputs are fixed rather than random so the file is reproducible: regenerating it after an unrelated change
// produces a byte-identical file, and a diff therefore means something.
//
//   dotnet run --project tools/DeskPair.Tools.Vectors -- <output.json>

using System.Buffers.Binary;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using DeskPair.Protocol;
using DeskPair.Protocol.Crypto;
using DeskPair.Protocol.Framing;

string output = args.Length > 0
    ? args[0]
    : Path.Combine(AppContext.BaseDirectory, "protocol-vectors.json");

var root = new JsonObject
{
    ["_comment"] = "Generated by tools/DeskPair.Tools.Vectors from DeskPair.Protocol. Do not edit by hand.",
    ["constants"] = Constants(),
    ["keys"] = Keys(),
    ["ecdh"] = Ecdh(),
    ["ecdsa"] = Ecdsa(),
    ["transcript"] = Transcripts(),
    ["hkdf"] = Hkdf(),
    ["cipher"] = Cipher(),
    ["passwordProof"] = PasswordProofs(),
    ["relayTicket"] = RelayTicketVectors(),
    ["framing"] = Framing(),
    ["clipboard"] = Clipboards(),
    ["connectLink"] = ConnectLinks(),
    ["media"] = Media(),
};

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
File.WriteAllText(output, root.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n");
Console.WriteLine($"Wrote {output}");
return 0;

static string Hex(ReadOnlySpan<byte> bytes) => Convert.ToHexStringLower(bytes);

// Everything the UDP media channel is made of: the three header layouts, a datagram sealed by the shipping
// cipher, and a Reed-Solomon block whose parity came from the encoder that actually runs. A phone only ever
// decodes, and a decode that is subtly wrong draws garbage rather than failing, so it is checked against the
// desktop's arithmetic instead of its own.
static JsonNode Media()
{
    // Header layouts, byte for byte. A field written at the wrong offset still round-trips through the
    // same code, so only the desktop's own bytes can catch it.
    var common = new DeskPair.Protocol.Media.MediaCommonHeader(
        DeskPair.Protocol.Media.MediaPacketType.Video,
        DeskPair.Protocol.Media.MediaPacketFlags.KeyFrame | DeskPair.Protocol.Media.MediaPacketFlags.LastShard,
        0x0102030405060708UL);
    byte[] commonBytes = new byte[DeskPair.Protocol.Media.MediaCommonHeader.Size];
    common.Write(commonBytes);

    var shard = new DeskPair.Protocol.Media.MediaShardHeader(
        Stream: 1, Codec: 2, BlockIndex: 1, BlockCount: 3,
        FrameSeq: 0x11223344u, PtsMs: 1_234_567_890L,
        ShardIndex: 5, K: 8, M: 4, ShardLength: 1100,
        FrameLength: 65_000u, Width: 2560, Height: 1440);
    byte[] shardBytes = new byte[DeskPair.Protocol.Media.MediaShardHeader.Size];
    shard.Write(shardBytes);

    var feedback = new DeskPair.Protocol.Media.MediaFeedback(
        Stream: 0, LossPermille: 37, HighestDecodableFrameSeq: 900u, LastFrameSeqReceived: 905u,
        EchoPacketSeq: 0xAABBCCDDUL, EchoDelayMicros: 12_345u, ReceivedBytes: 987_654_321UL,
        ReceiverClockMicros: 1_700_000_000_000UL, FramesGivenUp: 3u, ShardsRecovered: 17u);
    byte[] feedbackBytes = new byte[DeskPair.Protocol.Media.MediaFeedback.Size];
    feedback.Write(feedbackBytes);

    // A sealed datagram, so the phone's cipher is checked against a real one rather than against itself.
    byte[] mediaKey = Pattern(32, 0x51);
    byte[] mediaIv = Pattern(4, 0x52);
    using var cipher = new DeskPair.Protocol.Media.MediaCipher(mediaKey, mediaIv, mediaKey, mediaIv);
    var datagrams = new JsonArray();
    foreach (int length in new[] { 0, 1, 64, 517 })
    {
        byte[] plaintext = Pattern(length, 0x60);
        byte[] datagram = new byte[DeskPair.Protocol.Media.MediaCommonHeader.Size + length + DeskPair.Protocol.Media.MediaCipher.TagBytes];
        int written = cipher.Seal(DeskPair.Protocol.Media.MediaPacketType.Video, DeskPair.Protocol.Media.MediaPacketFlags.None, plaintext, datagram, out ulong seq);
        datagrams.Add(new JsonObject
        {
            ["packetSeq"] = seq,
            ["plaintext"] = Hex(plaintext),
            ["datagram"] = Hex(datagram.AsSpan(0, written)),
        });
    }

    // Reed-Solomon recovery, produced by the encoder that actually ships. Two data shards are dropped and
    // the parity that replaces them comes from the desktop, so a decoder that is subtly wrong disagrees
    // here rather than drawing garbage on someone's screen.
    const int k = 4, m = 2, shardLength = 64;
    var data = new ReadOnlyMemory<byte>[k];
    for (int i = 0; i < k; i++)
    {
        data[i] = Pattern(shardLength, (byte)(0x70 + i));
    }

    var parityBuffers = new Memory<byte>[m];
    for (int i = 0; i < m; i++)
    {
        parityBuffers[i] = new byte[shardLength];
    }

    DeskPair.Core.Transport.Udp.Fec.ReedSolomon.Encode(data, parityBuffers);

    var dataHex = new JsonArray();
    foreach (ReadOnlyMemory<byte> d in data)
    {
        dataHex.Add(Hex(d.Span));
    }

    var parityHex = new JsonArray();
    foreach (Memory<byte> p in parityBuffers)
    {
        parityHex.Add(Hex(p.Span));
    }

    var coefficients = new JsonArray();
    for (int row = 0; row < m; row++)
    {
        for (int col = 0; col < k; col++)
        {
            coefficients.Add(DeskPair.Core.Transport.Udp.Fec.ReedSolomon.Coefficient(k, row, col));
        }
    }

    return new JsonObject
    {
        ["commonHeader"] = new JsonObject
        {
            ["type"] = (int)common.Type,
            ["flags"] = (int)common.Flags,
            ["packetSeq"] = common.PacketSeq,
            ["bytes"] = Hex(commonBytes),
        },
        ["shardHeader"] = new JsonObject
        {
            ["stream"] = shard.Stream, ["codec"] = shard.Codec,
            ["blockIndex"] = shard.BlockIndex, ["blockCount"] = shard.BlockCount,
            ["frameSeq"] = shard.FrameSeq, ["ptsMs"] = shard.PtsMs,
            ["shardIndex"] = shard.ShardIndex, ["k"] = shard.K, ["m"] = shard.M,
            ["shardLength"] = shard.ShardLength, ["frameLength"] = shard.FrameLength,
            ["width"] = shard.Width, ["height"] = shard.Height,
            ["bytes"] = Hex(shardBytes),
        },
        ["feedback"] = new JsonObject
        {
            ["stream"] = feedback.Stream, ["lossPermille"] = feedback.LossPermille,
            ["highestDecodableFrameSeq"] = feedback.HighestDecodableFrameSeq,
            ["lastFrameSeqReceived"] = feedback.LastFrameSeqReceived,
            ["echoPacketSeq"] = feedback.EchoPacketSeq, ["echoDelayMicros"] = feedback.EchoDelayMicros,
            ["receivedBytes"] = feedback.ReceivedBytes, ["receiverClockMicros"] = feedback.ReceiverClockMicros,
            ["framesGivenUp"] = feedback.FramesGivenUp, ["shardsRecovered"] = feedback.ShardsRecovered,
            ["bytes"] = Hex(feedbackBytes),
        },
        ["cipher"] = new JsonObject
        {
            ["key"] = Hex(mediaKey),
            ["ivPrefix"] = Hex(mediaIv),
            ["datagrams"] = datagrams,
        },
        ["reedSolomon"] = new JsonObject
        {
            ["k"] = k, ["m"] = m, ["shardLength"] = shardLength,
            ["coefficients"] = coefficients,
            ["data"] = dataHex,
            ["parity"] = parityHex,
        },
    };
}

// The host puts its own content hash on the wire and the phone compares against it, so the two hashes have
