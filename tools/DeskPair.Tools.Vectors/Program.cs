static JsonNode Clipboards()
{
    var cases = new JsonArray();
    foreach ((string name, string text) in new[]
    {
        ("ascii", "hello from the desktop"),
        ("empty", ""),
        ("unicode", "剪貼簿 — 📋"),
        ("newlines", "first\r\nsecond\nthird"),
    })
    {
        var single = new DeskPair.Protocol.Messages.MultiClipboards
        {
            Items =
            {
                new DeskPair.Protocol.Messages.Clipboard
                {
                    Format = DeskPair.Protocol.Messages.ClipboardFormat.CfText,
                    Content = Google.Protobuf.ByteString.CopyFrom(Encoding.UTF8.GetBytes(text)),
                },
            },
        };

        cases.Add(new JsonObject
        {
            ["name"] = name,
            ["text"] = text,
            ["utf8"] = Hex(Encoding.UTF8.GetBytes(text)),
            ["hash"] = Hex(DeskPair.Core.Clipboard.ClipboardSync.Hash(single)),
        });
    }

    var mixed = new DeskPair.Protocol.Messages.MultiClipboards
    {
        Items =
        {
            // Deliberately out of format order: the hash sorts, and a reimplementation that does not will
            // disagree here rather than in the field.
            new DeskPair.Protocol.Messages.Clipboard
            {
                Format = DeskPair.Protocol.Messages.ClipboardFormat.CfHtml,
                Content = Google.Protobuf.ByteString.CopyFrom(Encoding.UTF8.GetBytes("<b>bold</b>")),
            },
            new DeskPair.Protocol.Messages.Clipboard
            {
                Format = DeskPair.Protocol.Messages.ClipboardFormat.CfText,
                Content = Google.Protobuf.ByteString.CopyFrom(Encoding.UTF8.GetBytes("bold")),
            },
        },
    };

    // A real PNG rather than three arbitrary bytes: the phone encodes one from a Bitmap or a UIImage, and a
    // vector built from something that is not a PNG would not notice if either side started re-encoding.
    byte[] png = SmallPng();

    var image = new DeskPair.Protocol.Messages.MultiClipboards
    {
        Items =
        {
            new DeskPair.Protocol.Messages.Clipboard
            {
                Format = DeskPair.Protocol.Messages.ClipboardFormat.CfImagePng,
                Content = Google.Protobuf.ByteString.CopyFrom(png),
            },
        },
    };

    // Text and an image together, with the image first — CF_TEXT is 0 and CF_IMAGE_PNG is 3, so a
    // reimplementation that hashes in arrival order disagrees here. This is the case the phone actually
    // produces when someone copies a picture and a caption.
    var textAndImage = new DeskPair.Protocol.Messages.MultiClipboards
    {
        Items =
        {
            new DeskPair.Protocol.Messages.Clipboard
            {
                Format = DeskPair.Protocol.Messages.ClipboardFormat.CfImagePng,
                Content = Google.Protobuf.ByteString.CopyFrom(png),
            },
            new DeskPair.Protocol.Messages.Clipboard
            {
                Format = DeskPair.Protocol.Messages.ClipboardFormat.CfText,
                Content = Google.Protobuf.ByteString.CopyFrom(Encoding.UTF8.GetBytes("a caption")),
            },
        },
    };

    return new JsonObject
    {
        ["text"] = cases,
        ["ordering"] = new JsonObject
        {
            ["html"] = "<b>bold</b>",
            ["text"] = "bold",
            ["hash"] = Hex(DeskPair.Core.Clipboard.ClipboardSync.Hash(mixed)),
        },
        ["image"] = new JsonObject
        {
            ["png"] = Hex(png),
            ["width"] = 4,
            ["height"] = 3,
            ["hash"] = Hex(DeskPair.Core.Clipboard.ClipboardSync.Hash(image)),
        },
        ["textAndImage"] = new JsonObject
        {
            ["text"] = "a caption",
            ["png"] = Hex(png),
            ["hash"] = Hex(DeskPair.Core.Clipboard.ClipboardSync.Hash(textAndImage)),
        },
        ["maxBytes"] = DeskPair.Protocol.ProtocolConstants.MaxClipboardBytes,
    };
}

// A 4x3 PNG from the shipping encoder, so the bytes are ones the product itself produces.
static byte[] SmallPng()
{
    const int width = 4, height = 3;
    byte[] bgra = new byte[width * height * 4];
    for (int i = 0; i < width * height; i++)
    {
        bgra[(i * 4) + 0] = (byte)(i * 20);        // blue
        bgra[(i * 4) + 1] = (byte)(255 - (i * 20)); // green
        bgra[(i * 4) + 2] = (byte)(i * 7);          // red
        bgra[(i * 4) + 3] = 0xFF;                   // opaque
    }

    return DeskPair.Platform.Abstractions.Imaging.PngCodec.Encode(bgra, width * 4, width, height);
}

// Deterministic filler, so the same run always produces the same file.
static byte[] Pattern(int length, byte seed)
{
    byte[] bytes = new byte[length];
    for (int i = 0; i < length; i++)
    {
        bytes[i] = (byte)((i * 31) + seed);
    }

    return bytes;
}

